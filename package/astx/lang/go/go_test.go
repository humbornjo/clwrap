package golang

import (
	"bytes"
	"io"
	"strings"
	"testing"

	"clwrap/package/comment"
)

func TestGolang_File(t *testing.T) {
	src := "// Package p documents the clause.\n" +
		"package p\n" +
		"\n" +
		"// Run documents the func.\n" +
		"func Run() {\n" +
		"\t// an inner comment\n" +
		"\tx := 1 // a trailing comment\n" +
		"\t_ = x\n" +
		"\t//go:generate echo a directive group\n" +
		"}\n" +
		"/* a block comment */\n"

	file, err := (Parser{}).Parse("x.go", []byte(src))
	if err != nil {
		t.Fatal(err)
	}

	var classes []comment.Class
	var first comment.Area
	for area := file.Next(); area != nil; area = file.Next() {
		if first == nil {
			first = area
		}
		classes = append(classes, area.Class())
	}
	want := []comment.Class{comment.CLASS_DOC, comment.CLASS_DOC, comment.CLASS_COMMENT}
	if len(classes) != len(want) {
		t.Fatalf("areas = %v, want %v (trailing, directive and block groups must not extract)", classes, want)
	}
	for i, c := range want {
		if classes[i] != c {
			t.Fatalf("area %d class = %v, want %v", i, classes[i], c)
		}
	}
	if file.Next() != nil {
		t.Fatal("a drained stream must keep yielding nil")
	}

	// A Reader streams its text exactly once: the second pass sees io.EOF from the start.
	text, err := io.ReadAll(first)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(text), "// Package p documents the clause.") {
		t.Fatalf("area text = %q", text)
	}
	if n, err := first.Read(make([]byte, 8)); n != 0 || err != io.EOF {
		t.Fatalf("drained read = %d, %v; want 0, io.EOF", n, err)
	}

	// A Writer overrides once: the replacement lands verbatim, the second write fails.
	if _, err := first.Write([]byte("// Package p documents the clause, wrapped.")); err != nil {
		t.Fatal(err)
	}
	if _, err := first.Write([]byte("// again")); err == nil {
		t.Fatal("second write must fail: an area overrides exactly once")
	}
	out := string(file.Source())
	if !strings.HasPrefix(out, "// Package p documents the clause, wrapped.\npackage p\n") {
		t.Fatalf("override not rendered:\n%s", out)
	}
	if len(out) != len(src)-len("// Package p documents the clause.")+len("// Package p documents the clause, wrapped.") {
		t.Fatalf("override changed bytes outside the area:\n%s", out)
	}

	// Nothing written, nothing changes.
	fresh, err := (Parser{}).Parse("x.go", []byte(src))
	if err != nil {
		t.Fatal(err)
	}
	for area := fresh.Next(); area != nil; area = fresh.Next() {
		if _, err := io.Copy(io.Discard, area); err != nil {
			t.Fatal(err)
		}
	}
	if got := fresh.Source(); !bytes.Equal(got, []byte(src)) {
		t.Fatalf("unwritten source drifted:\n%s", got)
	}
}

func TestGolang_ParseGenerated(t *testing.T) {
	src := "// Code generated by tool. DO NOT EDIT.\n\npackage p\n\n// Run documents the func in one very long line.\nfunc Run() {}\n"
	file, err := (Parser{}).Parse("x.go", []byte(src))
	if err != nil {
		t.Fatal(err)
	}
	if area := file.Next(); area != nil {
		t.Fatalf("generated file yielded an area: %v", area.Class())
	}
	if got := file.Source(); !bytes.Equal(got, []byte(src)) {
		t.Fatal("generated file must render untouched")
	}
}

func TestGolang_Extract(t *testing.T) {
	src := "package p\n\n" +
		"// D embeds the asset.\n" +
		"//\n" +
		"//go:embed all:dist\n" +
		"// D renders after the build.\n" +
		"var D int\n"

	file, err := (Parser{}).Parse("x.go", []byte(src))
	if err != nil {
		t.Fatal(err)
	}
	var runs []comment.Area
	for a := file.Next(); a != nil; a = file.Next() {
		if a.Class() != comment.CLASS_DOC {
			t.Fatalf("run class = %v, want CLASS_DOC", a.Class())
		}
		runs = append(runs, a)
	}
	if len(runs) != 2 {
		t.Fatalf("runs = %d, want the 2 prose runs around the directive", len(runs))
	}
	for i, want := range []string{"// D embeds the asset.\n//", "// D renders after the build."} {
		text, err := io.ReadAll(runs[i])
		if err != nil {
			t.Fatal(err)
		}
		if string(text) != want {
			t.Fatalf("run %d = %q, want %q", i, text, want)
		}
	}

	// An override rewrites only its own run: the directive between the runs renders verbatim.
	if _, err := runs[0].Write([]byte("// D embeds the asset, wrapped.\n//")); err != nil {
		t.Fatal(err)
	}
	out := string(file.Source())
	if !strings.Contains(out, "// D embeds the asset, wrapped.\n//\n//go:embed all:dist\n// D renders after the build.\nvar D int\n") {
		t.Fatalf("directive line did not survive the override:\n%s", out)
	}
}
